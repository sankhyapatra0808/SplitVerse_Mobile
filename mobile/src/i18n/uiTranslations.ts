function translateWords(value: string, language: AppLanguageCode) {
  const dictionary = wordTranslations[language];
  if (!dictionary) return value;

  return value.replace(
    /\b[A-Za-z][A-Za-z'-]*\b/g,
    (word) => dictionary[word] ?? word,
  );
}

export function translateUiText(value: string, language: AppLanguageCode) {
  if (language === "en") return value;
  const exact = exactTranslations[value]?.[language];
  if (exact) return exact;
  return translateWords(value, language);
}
