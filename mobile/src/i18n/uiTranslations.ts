function normalizeText(value: string) {
  return value.replace(/\s+/g, " ").trim();
}

export function translateUiText(value: string, language: AppLanguageCode) {
  if (language === "en") return value;
  const normalized = normalizeText(value);
  if (!normalized) return value;
  const exact = exactTranslations[normalized]?.[language];
  if (exact) return value.replace(normalized, exact);
  const words = wordTranslations[language] ?? {};
  const translated = normalized.replace(
    /\b[A-Za-z][A-Za-z&'-]*\b/g,
    (token) => {
      const clean = token.replace(/[&]/g, "");
      return words[token] ?? words[clean] ?? token;
    },
  );
  return value.replace(normalized, translated);
}
